'use client';

import React, { useState } from 'react';
import {
  Building2,
  MapPin,
  Mail,
  Phone,
  User,
  ShieldCheck,
  Users,
  CheckCircle2,
  AlertCircle,
  Loader2,
} from 'lucide-react';

